"""Supplementary tables, generated directly from the confirmatory CSVs (seeds 100-119).
Writes paper/latex/generated/S_*.tex.  No number is typed by hand."""
from pathlib import Path

import numpy as np
import pandas as pd

REPO = Path(__file__).resolve().parents[1]
T = REPO / "tables"; OUT = REPO / "paper/latex/generated"
EXCH = ["bbbp/random", "bbbp/scaffold", "b3db/random", "b3db/scaffold"]
LAB = {"bbbp/random": "BBBP random", "bbbp/scaffold": "BBBP scaffold", "b3db/random": "B3DB random",
       "b3db/scaffold": "B3DB scaffold", "bbbp→b3db/scaffold": "BBBP$\\to$B3DB", "bbbp/cluster": "BBBP cluster",
       "b3db/cluster": "B3DB cluster"}
MOD = {"rf": "RF", "gin": "GIN", "chemprop": "Chemprop"}
f2 = lambda x: "--" if pd.isna(x) else f"{x:.2f}"
f3 = lambda x: "--" if pd.isna(x) else f"{x:.3f}"
ci = lambda r, c: f"{r[c]:.2f} [{r[c + '_lo']:.2f}, {r[c + '_hi']:.2f}]"


def pval(p):
    return "$<$0.001" if p < 0.001 else f"{p:.3f}"


def tab(name, colspec, header, rows):
    with open(OUT / f"S_{name}.tex", "w") as f:
        f.write("% GENERATED by scripts/make_supplement_tables.py\n")
        f.write(f"\\begin{{tabular}}{{{colspec}}}\n\\toprule\n{header}\\\\\n\\midrule\n")
        f.write("\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")


S = pd.read_csv(T / "confirmatory_summary.csv", low_memory=False)
S = S[S.n_seeds == 20]
base = (S.score == "lac") & (S.alpha == 0.1) & (S.loss == "ce")


def row(st, md, meth, ext=None):
    m = base & (S.setting == st) & (S.model_name == md) & (S.method == meth)
    m &= S.external.isna() if ext is None else (S.external == ext)
    g = S[m]; assert len(g) == 1, (st, md, meth); return g.iloc[0]


# S1: per-cell coverage with CIs and counts
rows = []
for st in EXCH:
    for md in MOD:
        a, b = row(st, md, "mondrian"), row(st, md, "mondrian_x")
        rows.append(f"{LAB[st]} & {MOD[md]} & {a.n_cal_minority:.0f} & {a.n_test_minority:.0f} & {a.n_min_bin0:.0f} & "
                    f"{ci(a, 'cov_min_bin0')} & {ci(a, 'cov_min_bin2')} & {ci(b, 'cov_min_bin0')} & {ci(b, 'cov_min_bin2')}\\\\")
tab("cells", "llrrrcccc", "Setting & Model & $n^{-}_{\\mathrm{cal}}$ & $n^{-}_{\\mathrm{test}}$ & $n^{-}_{\\mathrm{low}}$ & "
    "Mondrian low & Mondrian high & C$\\times$S low & C$\\times$S high", rows)

# S2: the 36-member primary family with the cluster bootstrap
P = pd.read_csv(T / "confirmatory_paired_primary.csv")
B = pd.read_csv(T / "primary_cluster_bootstrap.csv")
rows = []
for _, r in P.iterrows():
    bm = B[(B.setting == r.setting) & (B.model == r.model) & (B.comparison == r.comparison) & (B.unit == "molecule")].iloc[0]
    bs = B[(B.setting == r.setting) & (B.model == r.model) & (B.comparison == r.comparison) & (B.unit == "scaffold")].iloc[0]
    comp = r.comparison.replace("mondrian_x", "C$\\times$S").replace("mondrian", "Mondrian").replace("sabm", "SABM")
    rows.append(f"{LAB[r.setting]} & {MOD[r.model]} & {comp} & {r.mean_diff:+.3f} & [{r.ci_lo:.3f}, {r.ci_hi:.3f}] & "
                f"{pval(r.wilcoxon_p)} & {pval(r.holm_p)} & [{bm.ci_lo:.3f}, {bm.ci_hi:.3f}] & {pval(bm.holm_p)} & {pval(bs.holm_p)}\\\\")
tab("primary", "lllrcccccc", "Setting & Model & Contrast & $\\Delta$ & Seed CI & $p$ & Holm$_{36}$ & Molecule CI & Holm$_{\\mathrm{mol}}$ & Holm$_{\\mathrm{scaf}}$", rows)

# S3: empirical settings (transfer, cluster)
rows = []
for st, ext in (("bbbp→b3db/scaffold", "b3db"), ("bbbp/cluster", None), ("b3db/cluster", None)):
    for md in MOD:
        mg, mo, mx = row(st, md, "marginal", ext), row(st, md, "mondrian", ext), row(st, md, "mondrian_x", ext)
        rows.append(f"{LAB[st]} & {MOD[md]} & {f2(mg.cov_minority)} & {f2(mo.cov_minority)} & {f2(mg.cov_majority)} & "
                    f"{f2(mo.cov_majority)} & {f2(mo.cov_min_bin0)} & {f2(mx.cov_min_bin0)} & {f2(mo.set_size)} & {f2(mx.set_size)}\\\\")
tab("shift", "llcccccccc", "Setting & Model & Marg.\\ BBB$-$ & Mond.\\ BBB$-$ & Marg.\\ BBB$+$ & Mond.\\ BBB$+$ & Mond.\\ low & C$\\times$S low & Size M & Size C$\\times$S", rows)

# S4: robustness (scores, alpha, support definitions), mean and range over the 12 exchangeable cells
ex = S.external.isna() & S.regime.isin(["random", "scaffold"]) & (S.loss == "ce")
rows = []
for lab, sc, al in (("LAC, $\\alpha=0.10$ (primary)", "lac", 0.1), ("APS, $\\alpha=0.10$", "aps", 0.1), ("RAPS, $\\alpha=0.10$", "raps", 0.1),
                    ("LAC, $\\alpha=0.05$", "lac", 0.05), ("LAC, $\\alpha=0.20$", "lac", 0.2)):
    g = S[ex & (S.score == sc) & (S.alpha == al)].pivot_table(index=["setting", "model_name"], columns="method", values="cov_min_bin0")
    d = g.mondrian_x - g.mondrian
    rows.append(f"{lab} & {g.mondrian.mean():.3f} ({g.mondrian.min():.2f}--{g.mondrian.max():.2f}) & "
                f"{g.mondrian_x.mean():.3f} ({g.mondrian_x.min():.2f}--{g.mondrian_x.max():.2f}) & {int((d > 0).sum())}/12\\\\")
tab("robust_scores", "lccc", "Score, level & Mondrian low & C$\\times$S low & cells with gain $>0$", rows)
g = S[ex & base].pivot_table(index=["setting", "model_name"], columns="method", values=["cov_min_bin0", "set_size"])
rows = []
for meth, lab in (("mondrian", "class only (Mondrian)"), ("mondrian_x", "max-Tanimoto tertiles (primary)"), ("mondrian_x_b2", "max-Tanimoto, 2 bins"),
                  ("mondrian_x_b5", "max-Tanimoto, 5 bins"), ("mondrian_x_top5", "mean top-5 Tanimoto tertiles"), ("mondrian_x_maccs", "MACCS max-Tanimoto tertiles"),
                  ("mondrian_kmeans3", "$k$-means clusters ($k=3$)"), ("mondrian_tpsa", "TPSA strata ($<60$, 60--90, $>90$)"),
                  ("mondrian_x_caledges", "tertile edges from CAL"), ("mondrian_x_random", "random strata (control)")):
    c, z = g["cov_min_bin0"][meth], g["set_size"][meth]
    rows.append(f"{lab} & {c.mean():.3f} & {c.min():.2f}--{c.max():.2f} & {z.mean():.3f}\\\\")
tab("robust_support", "lccc", "Second Mondrian dimension & low-support BBB$-$ (mean) & range & set size", rows)

# S5: common grid
G = pd.read_csv(T / "common_grid_summary.csv"); G = G[(G.n_seeds == 20) & (G.alpha == 0.1)]
G["n_min_cal"] = G.n_min_cal.astype(str)
rows = []
for nm in ("all", "160", "80", "40", "20", "10"):
    for meth in ("mondrian", "fixed_b2", "fixed_b3", "fixed_b5", "fixed_b8", "sabm_b3", "sabm_b8"):
        q = G[(G.n_min_cal == nm) & (G.method == meth)]
        if q.empty:
            continue
        rows.append(f"{'realized' if nm == 'all' else nm} & {meth.replace('_', '-')} & {len(q)} & {q.cov_min_t0.mean():.3f} & "
                    f"{q.worst_sextile_cov_min.mean():.3f} & {q.set_size.mean():.3f} & {q.singleton_rate.mean():.3f} & {q.degenerate_cell_frac.mean():.3f}\\\\")
    rows.append("\\midrule")
tab("grid", "llrccccc", "$n^{-}_{\\mathrm{cal}}$ & Partition & cells & low-tertile cov. & worst sextile & set size & singleton & degenerate", rows[:-1])

# S6: persistent failures, molecule list
W = pd.read_csv(T / "persistent_failure_molecules_ce.csv", low_memory=False)
Pm = W[W.cross_arch_mondrian.astype(bool)].sort_values(["setting", "TPSA"])
CUR = {"B3DB:2544": "curation error (name/structure)", "B3DB:3330": "curation error (mis-drawn)", "B3DB:3001": "curation error (mis-drawn)"}
rows = []
for _, r in Pm.iterrows():
    nm = str(r["name"]) if pd.notna(r["name"]) else r.mol_id
    nm = nm if not nm[:1].isdigit() else r.mol_id
    flag = CUR.get(r.mol_id, "B3DB: BBB$+$" if r.label_disagrees_other_dataset else "")
    rows.append(f"{LAB[r.setting]} & {nm.replace('_', ' ')} & {int(r.n_appear)} & {r.TPSA:.1f} & {int(r.HBD)} & {r.MW:.0f} & {r.cLogP:.2f} & {r.mean_sim_train:.2f} & {flag}\\\\")
tab("persist_list", "llrrrrrrl", "Setting & Compound & $k$ & TPSA & HBD & MW & cLogP & support & flag", rows)

# S7: descriptor contrasts (strict, majority)
